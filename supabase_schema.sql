-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    clips_count INTEGER DEFAULT 0,
    has_reviewed BOOLEAN DEFAULT FALSE,
    auth_token TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Index for fast lookup by email and auth_token
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users (email);
CREATE INDEX IF NOT EXISTS idx_users_auth_token ON public.users (auth_token);

-- 2. Reviews Table
CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users (id) ON DELETE SET NULL,
    user_email TEXT NOT NULL,
    rating INTEGER NOT NULL,
    review_text TEXT NOT NULL,
    owner_email TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_reviews_user_email ON public.reviews (user_email);

-- 3. Row Level Security (RLS) Setup
-- Enable RLS for data protection
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;

-- Allow full access for backend API using your anon/service key
DROP POLICY IF EXISTS "Allow backend API access for users" ON public.users;
CREATE POLICY "Allow backend API access for users" ON public.users
    FOR ALL
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow backend API access for reviews" ON public.reviews;
CREATE POLICY "Allow backend API access for reviews" ON public.reviews
    FOR ALL
    USING (true)
    WITH CHECK (true);
